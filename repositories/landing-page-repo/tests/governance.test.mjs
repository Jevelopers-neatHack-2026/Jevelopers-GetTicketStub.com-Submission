const root = fileURLToPath(new URL('../', import.meta.url));
const baselineRevision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
const html = await readFile(resolve(root, 'site/index.html'), 'utf8');
const copy = JSON.parse(await readFile(resolve(root, 'src/content/copy.json'), 'utf8'));
const proof = JSON.parse(await readFile(resolve(root, 'review/examples.json'), 'utf8'));
const cta = JSON.parse(await readFile(resolve(root, 'src/content/cta.json'), 'utf8'));
const now = new Date('2026-10-12T12:00:00Z');
const claim = copy.entries.find(entry => entry.id === 'LP-COPY-02');
const asset = proof.assets.find(entry => entry.path === 'site/assets/ballet-clean.webp');
const replacement = 'Synthetic governance dry run: illustrative preview only.';
const replacementPath = 'site/assets/withdrawn-example.svg';

// Original checked-in page/media are recorded source, not synthetic assets.
// Mutations below are explicitly synthetic, local and temporary; they are not
// owner approvals, a new immutable content audit, or deployed withdrawal evidence.
async function fixture(t) {
  const repository = await mkdtemp(resolve(tmpdir(), 'lp-governance-'));
  t.after(() => rm(repository, { recursive: true, force: true }));
  await cp(resolve(root, 'site'), resolve(repository, 'site'), { recursive: true });
  await mkdir(resolve(repository, 'src/content'), { recursive: true });
  await mkdir(resolve(repository, 'review'), { recursive: true });
  await writeFile(resolve(repository, 'src/content/copy.json'), JSON.stringify(copy));
  await writeFile(resolve(repository, 'review/examples.json'), JSON.stringify(proof));
  const build = async () => (await buildSite({ repository })).output;
  const verify = async (options = {}) => validateWithdrawal({ repository, auditRoot: root, artifactDir: await build(),
    baselineRevision, claimIds: [claim.id], assetPaths: [asset.path], ...options });
  return { repository, build, verify };
}

async function withdraw(repository) {
  const changed = html.replaceAll(claim.exactCopy, replacement).replaceAll(asset.path.replace(/^site\//, ''), replacementPath.replace(/^site\//, ''));
  assert.notEqual(changed, html);
  await writeFile(resolve(repository, 'site/index.html'), changed);
  await rm(resolve(repository, asset.path));
  // Safe text-only replacement generated by this test. No media processing,
  // provider output, publication rights or visual review result is invented.
  const bytes = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180"><title>Illustrative replacement: local governance test only</title><rect width="320" height="180" fill="#eee"/><text x="10" y="90">Illustrative replacement</text></svg>');
  await writeFile(resolve(repository, replacementPath), bytes);
  const updatedCopy = structuredClone(copy);
  updatedCopy.entries.find(entry => entry.id === claim.id).exactCopy = replacement;
  const updatedProof = structuredClone(proof);
  Object.assign(updatedProof.assets.find(entry => entry.path === asset.path), { path: replacementPath, sha256: digest(bytes) });
  for (const scene of updatedProof.scenes) if (scene.asset === asset.path) scene.asset = replacementPath;
  // Keep real audit pins unchanged: this removal-only test must not claim that
  // a locally changed candidate has received a new immutable content audit.
  await writeFile(resolve(repository, 'src/content/copy.json'), JSON.stringify(updatedCopy));
  await writeFile(resolve(repository, 'review/examples.json'), JSON.stringify(updatedProof));
  return changed;
}

test('LP-09 supported update: replay the retained physical-to-illustrative correction as a pending draft', async () => {
  const historical = readAuditedFile(root, copy.source.revision, 'site/index.html').toString('utf8');
  assert.ok(historical.includes('Printed on heavy card'));
  assert.ok(!html.includes('Printed on heavy card'));
  assert.ok(html.includes('printing and shipping pending'));
  assert.equal(validateContent(html, copy, { root, now }).status, 'PASS_DRAFT');
  assert.equal((await validateProof({ root, manifest: proof, html, now })).status, 'PASS_DRAFT');
  assert.ok(copy.entries.every(entry => entry.approval === 'PENDING'));
});

test('LP-09 unsupported/stale update: rehashing or changing an approval label cannot publish a claim', async () => {
  const changed = html.replace(claim.exactCopy, 'Buy for $9.99; ships within 72 hours.');
  const bad = structuredClone(copy);
  bad.pageSha256 = digest(changed); bad.visibleTextSha256 = digest(visibleText(changed));
  assert.throws(() => validateContent(changed, bad, { root, now }), /Audited source bytes differ/);
  const expired = structuredClone(copy);
  expired.entries[0].recheckBy = '2026-10-11'; expired.entries[0].approval = 'APPROVED';
  assert.throws(() => validateContent(html, expired, { root, mode: 'release', now }), /stale/);
  const expiredProof = structuredClone(proof); expiredProof.recheckBy = '2026-10-11';
  await assert.rejects(validateProof({ root, manifest: expiredProof, html, mode: 'release', now }), /Stale example/);
});

test('LP-09 withdrawal: real built claim/asset disappear, a safe local replacement is present, rollback restores exact bytes', async t => {
  const f = await fixture(t);
  const before = await readFile(resolve(await f.build(), 'manifest.json'));
  const changed = await withdraw(f.repository);
  const result = await f.verify();
  assert.equal(result.status, 'PASS_LOCAL');
  const output = resolve(f.repository, 'dist/site');
  const built = await readFile(resolve(output, 'index.html'), 'utf8');
  assert.ok(built.includes(replacement)); assert.ok(built.includes(replacementPath.replace(/^site\//, '')));
  assert.ok(built.includes(proof.fallback.staticDescription));
  assert.equal(validateCtaSource(changed, cta).destination, 'https://getticketstub.com/make');
  // The temporary replacement deliberately has no immutable current audit.
  assert.throws(() => validateContent(changed, copy, { root, now }), /Unreviewed source\/copy/);
  await rm(resolve(f.repository, 'site'), { recursive: true });
  await cp(resolve(root, 'site'), resolve(f.repository, 'site'), { recursive: true });
  await writeFile(resolve(f.repository, 'src/content/copy.json'), JSON.stringify(copy));
  await writeFile(resolve(f.repository, 'review/examples.json'), JSON.stringify(proof));
  const rollbackOutput = await f.build();
  await validateArtifact(f.repository, rollbackOutput);
  assert.deepEqual(await readFile(resolve(rollbackOutput, 'manifest.json')), before);
  // Rollback here is a local drill; restoring withdrawn content for publication
  // would require renewed permission and freshness review.
  await assert.rejects(f.verify(), /Withdrawn claim remains/);
});

test('withdrawal rejects stale active inventories and hiding content in comments', async t => {
  const f = await fixture(t);
  await withdraw(f.repository);
  await writeFile(resolve(f.repository, 'src/content/copy.json'), JSON.stringify(copy));
  await assert.rejects(f.verify(), /active copy inventory/);
  const revised = structuredClone(copy); revised.entries.find(entry => entry.id === claim.id).exactCopy = replacement;
  await writeFile(resolve(f.repository, 'src/content/copy.json'), JSON.stringify(revised));
  const path = resolve(f.repository, 'site/index.html');
  await writeFile(path, `${await readFile(path, 'utf8')}\n<!-- ${claim.exactCopy} -->\n`);
  await assert.rejects(f.verify(), /Withdrawn claim remains in public payload/);
});

test('withdrawal rejects original asset bytes under a renamed file and a stale scene reference', async t => {
  const f = await fixture(t);
  await withdraw(f.repository);
  await cp(resolve(root, asset.path), resolve(f.repository, 'site/assets/renamed-withdrawn.webp'));
  await assert.rejects(f.verify(), /Withdrawn asset bytes remain/);
  await rm(resolve(f.repository, 'site/assets/renamed-withdrawn.webp'));
  const currentProof = JSON.parse(await readFile(resolve(f.repository, 'review/examples.json'), 'utf8'));
  currentProof.scenes[0].asset = asset.path;
  await writeFile(resolve(f.repository, 'review/examples.json'), JSON.stringify(currentProof));
  await assert.rejects(f.verify(), /Withdrawn scene reference/);
});

test('GOV-R1: character references cannot retain withdrawn rendered text or attributes', async t => {
  const variants = [
    ['decimal', '&#80;in the nights that mattered.'],
    ['hexadecimal', '&#x50;in the nights that mattered.'],
    ['omitted numeric semicolon', '&#80in the nights that mattered.'],
    ['encoded whitespace', 'Pin&#32;the nights that mattered.'],
    ['named whitespace', 'Pin&Tab;the nights that mattered.'],
    ['legacy whitespace without semicolon', 'Pin&nbsp the nights that mattered.'],
    ['unsupported named reference', 'Pin the nights that mattered&period;'],
    ['unsupported legacy prefix', 'Removed &copyholder preview'],
    ['inline element split', '<span>&#80;</span>in the nights that mattered.'],
    ['accessible attribute', '<span aria-label="&#80;in the nights that mattered.">Removed preview label</span>'],
  ];
  for (const [label, encoded] of variants) await t.test(label, async context => {
    const f = await fixture(context);
    const updated = structuredClone(copy);
    updated.entries = updated.entries.filter(entry => entry.id !== claim.id);
    await writeFile(resolve(f.repository, 'src/content/copy.json'), JSON.stringify(updated));
    await writeFile(resolve(f.repository, 'site/index.html'), html.replaceAll(claim.exactCopy, encoded));
    await assert.rejects(f.verify({ assetPaths: [] }), /Withdrawn claim remains|Unsupported HTML character reference/);
  });
});

test('a once-escaped character reference remains literal text instead of being recursively decoded', async t => {
  const f = await fixture(t);
  const updated = structuredClone(copy);
  updated.entries = updated.entries.filter(entry => entry.id !== claim.id);
  await writeFile(resolve(f.repository, 'src/content/copy.json'), JSON.stringify(updated));
  await writeFile(resolve(f.repository, 'site/index.html'), html.replaceAll(claim.exactCopy, '&amp;#80;in the nights that mattered.'));
  assert.equal((await f.verify({ assetPaths: [] })).status, 'PASS_LOCAL');
});

test('GOV-R2: renamed and padded public payloads cannot retain the complete original asset bytes', async t => {
  const originalBytes = await readFile(resolve(root, asset.path));
  for (const [label, bytes] of [
    ['original followed by newline', Buffer.concat([originalBytes, Buffer.from('\n')])],
    ['original embedded between padding', Buffer.concat([Buffer.from('SYNTHETIC_PREFIX'), originalBytes, Buffer.from('\n')])],
  ]) await t.test(label, async context => {
    const f = await fixture(context);
    const renamed = 'site/assets/renamed-ballet.webp';
    await rm(resolve(f.repository, asset.path));
    await writeFile(resolve(f.repository, renamed), bytes);
    await writeFile(resolve(f.repository, 'site/index.html'), html.replaceAll(asset.path.replace(/^site\//, ''), renamed.replace(/^site\//, '')));
    const updated = structuredClone(proof);
    Object.assign(updated.assets.find(entry => entry.path === asset.path), { path: renamed, sha256: digest(bytes) });
    for (const scene of updated.scenes) if (scene.asset === asset.path) scene.asset = renamed;
    await writeFile(resolve(f.repository, 'review/examples.json'), JSON.stringify(updated));
    assert.notEqual(digest(bytes), asset.sha256);
    assert.ok(bytes.includes(originalBytes));
    await assert.rejects(f.verify({ claimIds: [] }), /Withdrawn asset bytes remain/);
  });
});

test('withdrawal requires an immutable known nonempty selection and rejects still-packaged media', async t => {
  const f = await fixture(t);
  await assert.rejects(f.verify({ claimIds: [], assetPaths: [] }), /Select at least one/);
  await assert.rejects(f.verify({ baselineRevision: 'main' }), /immutable commit/);
  await assert.rejects(f.verify({ claimIds: ['UNKNOWN'], assetPaths: [] }), /Unknown or ambiguous/);
  await assert.rejects(f.verify({ claimIds: [claim.id, claim.id], assetPaths: [] }), /Duplicate/);
  await withdraw(f.repository);
  await cp(resolve(root, asset.path), resolve(f.repository, asset.path));
  await assert.rejects(f.verify(), /Withdrawn asset remains packaged/);
});

