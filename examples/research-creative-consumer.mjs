import assert from 'node:assert/strict';
import { checkResearchCreative, adaptResearchPackage, researchContentHash } from '@jevelopers/shared-contracts/research-creative';
import project from '@jevelopers/shared-contracts/fixtures/ProjectRequest.json' with { type: 'json' };
import pkg from '@jevelopers/shared-contracts/fixtures/EventIntelligencePackage.json' with { type: 'json' };
import design from '@jevelopers/shared-contracts/fixtures/DesignVersion.json' with { type: 'json' };
const serverScope = { tenant_id: '123e4567-e89b-42d3-a456-426614174000', project_id: '123e4567-e89b-42d3-a456-426614174000' };
const context = fixture => ({ ...structuredClone(fixture.cases.find(c => c.id === 'semantic-positive').context), scope: serverScope });
assert.equal(checkResearchCreative('ProjectRequest', project.valid, context(project)).ok, true);
assert.deepEqual(checkResearchCreative('ProjectRequest', { ...project.valid, tenant_id: '123e4567-e89b-42d3-a456-000000000999' }, context(project)), { ok: false, errors: [{ code: 'SCOPE_MISMATCH', path: '/tenant_id' }] });
assert.equal(checkResearchCreative('EventIntelligencePackage', pkg.valid, context(pkg)).ok, true);
const revoked = context(pkg);
revoked.approvals[pkg.valid.approved_assets[0].approval_ref.id].status = 'revoked';
assert.equal(checkResearchCreative('EventIntelligencePackage', pkg.valid, revoked).ok, false);
const alias = { ...pkg.valid, contract: 'ResearchPackage' };
const adapted = adaptResearchPackage(alias, 'canonical-alias-1.0.0');
assert.equal(adapted.ok, true);
if (!adapted.ok) throw new Error('Alias adapter rejected');
assert.equal(adapted.value.accepted_migration, false);
assert.deepEqual(adapted.value.source, alias);
assert.deepEqual(adapted.value.candidate, pkg.valid);
assert.equal(researchContentHash(pkg.valid, 'package_hash'), pkg.valid.package_hash);
const designContext = context(design);
designContext.artifact_bytes = Object.fromEntries(Object.entries(designContext.artifact_bytes).map(([id, bytes]) => [id, Uint8Array.from(bytes)]));
assert.equal(checkResearchCreative('DesignVersion', design.valid, designContext).ok, true);
designContext.artifact_bytes[design.valid.artwork.artifact_id] = Uint8Array.from([9, 9, 9]);
assert.equal(checkResearchCreative('DesignVersion', design.valid, designContext).ok, false);
console.log(JSON.stringify({ status: 'passed', node: process.version, dependency_mode: 'offline_installed_research_creative', provider_calls: 0, cases: ['independent_scope', 'forged_scope', 'package_provenance', 'revoked_asset', 'explicit_alias', 'canonical_manifest', 'artwork_preview_bytes'] }));
